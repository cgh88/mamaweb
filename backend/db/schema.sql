-- 마마치킨 DB 스키마 (PostgreSQL 18)
-- 서버 시작 시마다 실행되므로 모든 구문은 반복 실행해도 안전해야 함 (IF NOT EXISTS)

-- 소스 치킨 서브탭 (순서 고정: 아메리칸 징 ~ 삼양불닭)
CREATE TABLE IF NOT EXISTS sauce_tabs (
  name       TEXT PRIMARY KEY,
  image      TEXT NOT NULL DEFAULT '',
  sort_order INTEGER NOT NULL
);

-- 메뉴: 목록 순서는 id 오름차순 (기존 menu.json 배열 순서와 동일)
CREATE TABLE IF NOT EXISTS menu_items (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category    TEXT NOT NULL,
  sub_tab     TEXT REFERENCES sauce_tabs (name) ON UPDATE CASCADE,
  name        TEXT NOT NULL,
  name_en     TEXT NOT NULL DEFAULT '',
  image       TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  origin      TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS menu_items_category_idx ON menu_items (category, sub_tab);

-- 게시글: 새소식(notice) / 이벤트(event)
-- date는 기존 데이터 형식('2024-07-19' 또는 '2024-07-19 20:01:52')을 그대로 보존하기 위해 TEXT
CREATE TABLE IF NOT EXISTS posts (
  idx        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type       TEXT NOT NULL CHECK (type IN ('notice', 'event')),
  title      TEXT NOT NULL,
  date       TEXT NOT NULL,
  start_date DATE,
  end_date   DATE,
  thumbnail  TEXT,
  content    TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS posts_type_date_idx ON posts (type, date DESC);

-- 매장
CREATE TABLE IF NOT EXISTS stores (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  short_name TEXT NOT NULL DEFAULT '',
  city       TEXT NOT NULL,
  district   TEXT NOT NULL,
  address    TEXT NOT NULL,
  phone      TEXT NOT NULL DEFAULT '',
  hours      TEXT[] NOT NULL DEFAULT '{}',
  map_embed  TEXT NOT NULL DEFAULT ''
);

-- 홈 상단 슬라이드 배너
CREATE TABLE IF NOT EXISTS banners (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  image      TEXT NOT NULL,
  sort_order INTEGER NOT NULL
);

-- 구조가 자유로운 사이트 설정 (key 'home' = 홈 화면 신메뉴/추천메뉴/추천사이드)
CREATE TABLE IF NOT EXISTS site_settings (
  key        TEXT PRIMARY KEY,
  value      JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 관리자 비밀번호(scrypt 해시) + 접속 허용 IP — 항상 1행
CREATE TABLE IF NOT EXISTS admin_auth (
  id          SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  salt        TEXT NOT NULL,
  hash        TEXT NOT NULL,
  is_default  BOOLEAN NOT NULL DEFAULT false,
  allowed_ips TEXT[] NOT NULL DEFAULT '{}',
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 관리자 세션: 토큰 원문은 저장하지 않고 SHA-256 해시만 보관 (서버 재시작해도 로그인 유지)
CREATE TABLE IF NOT EXISTS admin_sessions (
  token_hash TEXT PRIMARY KEY,
  expires_at TIMESTAMPTZ NOT NULL
);
